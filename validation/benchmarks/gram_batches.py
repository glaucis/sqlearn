"""Measure the ways to cut the batches of a Gram learn (issue #66).

A Gram learn (``sqlearn._gram.gram_matrix``) needs XᵀX of the centred
columns, summed in numpy from batches DuckDB hands over. This script times
the ways to cut those batches that need only duckdb and numpy:

- ``table``: the centred rows numbered into a temporary table, fetched by
  row range with ``fetchnumpy`` (``gram_matrix`` as it is);
- ``fetchmany``: one streaming result of the centred rows, read with
  ``fetchmany`` into ``numpy.array``;
- ``file``: the source read again for each batch by ``file_row_number``
  range, centred on the fly (only when the source is one Parquet file).

It times each on 1,000,000 rows of 50, 200 and 500 columns, and the
``table`` way on 1,000,000 and 4,000,000 rows of 50 columns to show how its
time grows with the rows. Each probe runs in a subprocess of its own, and
prints a checksum of its matrix so that the ways can be seen to agree. It
prints Markdown tables. It measures; it decides nothing.

Run it with ``uv run python -m validation.benchmarks.gram_batches``. The data
is generated by DuckDB from a fixed seed into a temporary directory removed
after, and written as Parquet with ``COPY``. ``uptime`` is printed before and
after: on a loaded machine the times are estimates.
"""

import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import duckdb
import numpy as np

from sqlearn._expr import quote
from sqlearn._gram import batch_rows, gram_matrix
from validation.benchmarks.category_lookup import _machine

PAGE = "docs/benchmarks/gram-batches.md"
"""The page of ``docs/benchmarks`` this script's numbers feed."""
GROUPS: tuple[str, ...] | None = None
"""The C++ groups it measures; None for every group (ADR 0072)."""

SEED = 0
"""Every dataset comes from this seed: generated, never downloaded."""

WIDTHS = (50, 200, 500)
"""The columns measured at one million rows."""

ROWS = 1_000_000
"""The rows of the width measurements."""

GROWTH = (1_000_000, 4_000_000)
"""The rows measured at the first width, to show how the time grows."""

WAYS = ("table", "fetchmany", "file")
"""The ways to cut the batches."""


def _uptime() -> str:
    return subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip()


def _write(path: Path, rows: int, columns: int) -> None:
    """Write `rows` rows of `columns` columns of spread values as Parquet."""
    values = ", ".join(
        f"((hash(i, {SEED + j}) % 2000001)::DOUBLE - 1000000) / 10000 AS c{j}"
        for j in range(columns)
    )
    con = duckdb.connect()
    con.execute(
        f"COPY (SELECT {values} FROM range({rows}) t(i)) TO '{path}' (FORMAT parquet)"
    )
    con.close()


def _centred(source: str, names: list[str], means: list[float]) -> str:
    """Return the query of the source's columns less their means."""
    cols = ", ".join(
        f"({quote(n)}::DOUBLE - '{m!r}'::DOUBLE) AS {quote(f'x{j}')}"
        for j, (n, m) in enumerate(zip(names, means, strict=True))
    )
    return f"SELECT {cols} FROM {source}"


def _fetchmany(con: duckdb.DuckDBPyConnection, query: str, columns: int) -> np.ndarray:
    size = batch_rows(columns)
    gram = np.zeros((columns, columns))
    result = con.execute(query)
    while True:
        rows = result.fetchmany(size)
        if not rows:
            return gram
        batch = np.array(rows, dtype=float)
        gram += batch.T @ batch


def _file(
    con: duckdb.DuckDBPyConnection, path: Path, names: list[str], means: list[float]
) -> np.ndarray:
    columns = len(names)
    size = batch_rows(columns)
    source = f"read_parquet('{path}', file_row_number = true)"
    total = con.execute(f"SELECT count(*) FROM {source}").fetchall()[0][0]
    gram = np.zeros((columns, columns))
    for start in range(0, total, size):
        query = _centred(source, names, means) + (
            f" WHERE file_row_number >= {start} AND file_row_number < {start + size}"
        )
        batch = con.execute(query).fetchnumpy()
        rows = np.column_stack([np.ma.getdata(batch[f"x{j}"]) for j in range(columns)])
        gram += rows.T @ rows
    return gram


def probe(way: str, path: Path) -> None:
    """Time one way on one file, in this process; print a JSON line."""
    con = duckdb.connect()
    source = f"read_parquet('{path}')"
    names = [r[0] for r in con.execute(f"DESCRIBE SELECT * FROM {source}").fetchall()]
    avgs = ", ".join(f"avg({quote(n)})" for n in names)
    means = [
        float(m) for m in con.execute(f"SELECT {avgs} FROM {source}").fetchall()[0]
    ]
    start = time.perf_counter()
    if way == "table":
        gram = gram_matrix(
            con, f"SELECT * FROM {source}", names, dict(zip(names, means, strict=True))
        )
    elif way == "fetchmany":
        gram = _fetchmany(con, _centred(source, names, means), len(names))
    else:
        gram = _file(con, path, names, means)
    seconds = time.perf_counter() - start
    print(json.dumps({"s": round(seconds, 2), "trace": float(np.trace(gram))}))  # noqa: T201


def _run(way: str, path: Path) -> dict:
    out = subprocess.run(
        [
            sys.executable,
            "-m",
            "validation.benchmarks.gram_batches",
            "probe",
            way,
            str(path),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if out.returncode:
        return {"s": "failed", "trace": out.stderr.strip().splitlines()[-1][:60]}
    return json.loads(out.stdout.strip().splitlines()[-1])


def main() -> None:
    """Generate the data, time every way, print the tables."""
    if sys.argv[1:2] == ["probe"]:
        probe(sys.argv[2], Path(sys.argv[3]))
        return
    print(json.dumps(_machine(), indent=2))  # noqa: T201
    print("\nuptime before:", _uptime())  # noqa: T201
    with tempfile.TemporaryDirectory(prefix="gram_batches_") as tmp:
        path = Path(tmp) / "data.parquet"
        print(  # noqa: T201
            "\n| rows | columns | way | s | trace |\n|---|---|---|---|---|", flush=True
        )
        for columns in WIDTHS:
            _write(path, ROWS, columns)
            for way in WAYS:
                r = _run(way, path)
                print(  # noqa: T201
                    f"| {ROWS:,} | {columns} | {way} | {r['s']} | {r['trace']!r} |",
                    flush=True,
                )
        for rows in GROWTH:
            _write(path, rows, WIDTHS[0])
            for way in ("table", "file"):
                r = _run(way, path)
                print(  # noqa: T201
                    f"| {rows:,} | {WIDTHS[0]} | {way} | {r['s']} | {r['trace']!r} |",
                    flush=True,
                )
    print("\nuptime after:", _uptime())  # noqa: T201


if __name__ == "__main__":
    main()
