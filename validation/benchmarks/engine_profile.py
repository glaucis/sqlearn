"""Profile where sqlearn's heavy paths spend their time (issue #78).

Before computation moves to C++, this measures the paths that matter most
today: ``pca``, ``spearman`` (``sq.explore.correlations``), ``scale``,
``median``, ``variance`` and ``profile``, on 1,000,000 rows of 50, 200 and 500
columns (not every path at every width). Each case runs in a subprocess of its
own, twice for timing and once profiled. The profiled run sets DuckDB's JSON
profiling, so that every statement the call sends is caught with its time, its
peak buffer memory and its operators, and wraps the call in ``cProfile``, so
that the time spent in Python can be told from the time spent in DuckDB. It
prints one Markdown row per case and writes every result as JSON. It
measures; it decides nothing.

Run it with ``uv run python -m validation.benchmarks.engine_profile --json
PATH``. The data is generated by DuckDB from a fixed seed into a temporary
directory removed after, and written as Parquet with ``COPY``. ``uptime`` is
printed before and after: on a loaded machine the times are estimates.
"""

import cProfile
import json
import pstats
import re
import subprocess
import sys
import tempfile
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any, TypedDict

import duckdb

import sqlearn as sq
from validation.benchmarks.category_lookup import _machine
from validation.benchmarks.gram_batches import _write
from validation.benchmarks.gram_reach import _peak

PAGE = "docs/benchmarks/engine-profile.md"
"""The page of ``docs/benchmarks`` this script's numbers feed."""
GROUPS: tuple[str, ...] | None = None
"""The C++ groups it measures; None for every group (ADR 0072)."""

ROWS = 1_000_000
"""The rows of every case."""

TIMEOUT = 1800
"""The seconds a probe may take."""

CASES: tuple[tuple[str, int], ...] = (
    ("pca", 50),
    ("pca", 200),
    ("pca", 500),
    ("spearman", 50),
    ("spearman", 200),
    *(
        (call, width)
        for call in ("scale", "median", "variance", "profile")
        for width in (200, 500)
    ),
)
"""The call and the width of each case, in the order they run."""

CALLS: dict[str, Callable[[str], object]] = {
    "pca": lambda path: sq.Pipeline([sq.decompose.pca()]).learn(path),
    "spearman": lambda path: sq.explore.correlations(
        path, method="spearman"
    ).fetchall(),
    "scale": lambda path: sq.Pipeline([sq.scale.standard()]).learn(path),
    "median": lambda path: sq.Pipeline([sq.impute.median()]).learn(path),
    "variance": lambda path: sq.Pipeline([sq.select.variance()]).learn(path),
    "profile": lambda path: sq.explore.profile(path).fetchall(),
}
"""Each call, taking the path of a Parquet file."""


class Statement(TypedDict):
    """One statement's profile, as DuckDB reports it."""

    sql: str
    seconds: float
    cpu_seconds: float
    peak_buffer_bytes: int
    temp_bytes: int
    operators: list[tuple[str, float]]


def _operator_times(nodes: list[dict], totals: dict[str, float]) -> None:
    for node in nodes:
        totals[node["type"]] = totals.get(node["type"], 0.0) + node["timing"]
        _operator_times(node.get("children", []), totals)


def parse_profiles(text: str) -> list[Statement]:
    """Return every profile in `text`, in order; other text is skipped."""
    decoder = json.JSONDecoder()
    found: list[Statement] = []
    at = text.find("{")
    while at != -1:
        try:
            obj, end = decoder.raw_decode(text, at)
        except ValueError:
            at = text.find("{", at + 1)
            continue
        if isinstance(obj, dict) and "query" in obj:
            totals: dict[str, float] = {}
            _operator_times(obj.get("operator", []), totals)
            found.append(
                Statement(
                    sql=obj["query"]["sql"],
                    seconds=obj["query"]["total_time"],
                    cpu_seconds=obj["query"]["cpu_time"],
                    peak_buffer_bytes=obj["system"]["peak_buffer_memory"],
                    temp_bytes=obj["system"]["peak_temp_dir_size"],
                    operators=sorted(totals.items(), key=lambda kv: (-kv[1], kv[0])),
                )
            )
        at = text.find("{", end if isinstance(obj, dict) else at + 1)
    return found


def _uptime() -> str:
    return subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip()


def probe(call: str, path: str, result: str, profiled: bool) -> None:
    """Run one call on one file, in this process; write its JSON to `result`."""
    con = duckdb.connect()
    sq.set_config(connection=con)
    # Read before profiling starts, so these queries are not profiled.
    # fetchall() ends each result: an unfinished one would block the call.
    threads = con.execute("SELECT current_setting('threads')").fetchall()[0][0]
    memory_limit = con.execute("SELECT current_setting('memory_limit')").fetchall()[0][
        0
    ]
    if profiled:
        con.execute("SET enable_profiling = 'json'")
    profiler = cProfile.Profile() if profiled else None
    start = time.perf_counter()
    if profiler:
        profiler.runcall(CALLS[call], path)
    else:
        CALLS[call](path)
    seconds = time.perf_counter() - start
    out: dict[str, Any] = {
        "s": seconds,
        "peak_gb": _peak() / 1e9,
        "threads": threads,
        "memory_limit": memory_limit,
    }
    if profiler:
        stats = pstats.Stats(profiler).stats  # type: ignore[attr-defined]
        own = [
            (f"{file}:{line}({name})", tottime)
            for (file, line, name), (_, _, tottime, _, _) in stats.items()
            # DuckDB's nanobind methods are not separate cProfile entries
            # (their time lands in the calling function's tottime), so this
            # drops only Python wrappers with "duckdb" in their name.
            if "duckdb" not in name.lower()
        ]
        own.sort(key=lambda item: -item[1])
        out["python_top"] = [[name, secs] for name, secs in own[:5]]
    Path(result).write_text(json.dumps(out))


def _failure(returncode: int, stderr: str) -> str:
    """Return why a probe failed, in at most 80 characters.

    A probe killed by a signal has a negative return code. Otherwise the cause
    is the last line of stderr outside any profile JSON a profiled probe printed.
    """
    if returncode < 0:
        return f"killed by signal {-returncode}"
    decoder = json.JSONDecoder()
    kept: list[str] = []
    at = 0
    while at < len(stderr):
        start = stderr.find("{", at)
        if start == -1:
            break
        try:
            _, end = decoder.raw_decode(stderr, start)
        except ValueError:
            kept.append(stderr[at : start + 1])
            at = start + 1
            continue
        kept.append(stderr[at:start])
        at = end
    kept.append(stderr[at:])
    # DuckDB's leak report, printed at exit after any traceback, is noise; its
    # last line may be glued to the text before it.
    text = re.sub(r"See https://nanobind\S*", "", "".join(kept))
    lines = [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not line.lstrip().startswith(("nanobind:", "- leaked"))
    ]
    return (lines[-1] if lines else "no error")[:80]


def run(call: str, path: Path, profiled: bool) -> dict[str, Any]:
    """Run a probe in a subprocess; return its result, or why it failed.

    A profiled run's wall time includes cProfile's overhead, which counts
    toward Python's share.
    """
    with tempfile.TemporaryDirectory(prefix="engine_profile_") as tmp:
        result = Path(tmp) / "result.json"
        try:
            out = subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "validation.benchmarks.engine_profile",
                    "probe",
                    call,
                    str(path),
                    str(result),
                    "1" if profiled else "0",
                ],
                capture_output=True,
                text=True,
                check=False,
                timeout=TIMEOUT,
            )
        except subprocess.TimeoutExpired:
            return {"s": "failed", "error": "timed out"}
        if out.returncode:
            return {"s": "failed", "error": _failure(out.returncode, out.stderr)}
        data = json.loads(result.read_text())
    # DuckDB 2.0 prints each profile to stderr here, so both streams are read.
    if profiled:
        statements = parse_profiles(out.stdout + out.stderr)
        duckdb_s = sum(s["seconds"] for s in statements)
        data["statements"] = statements
        data["duckdb_s"] = duckdb_s
        data["python_s"] = data["s"] - duckdb_s
    return data


def _row(
    call: str, width: int, runs: list[dict[str, Any]], profiled: dict[str, Any]
) -> str:
    def fmt(value: object) -> str:
        return f"{value:.2f}" if isinstance(value, float) else str(value)

    seconds = " / ".join(fmt(r["s"]) for r in runs)
    peaks = " / ".join(fmt(r.get("peak_gb", "-")) for r in runs)
    statements = profiled.get("statements", [])
    longest = max(statements, key=lambda s: s["seconds"], default=None)
    top = (
        ", ".join(f"{n} {t:.2f}" for n, t in longest["operators"][:3])
        if longest
        else "-"
    )
    return (
        f"| {call} | {width} | {seconds} | {peaks} "
        f"| {fmt(profiled.get('duckdb_s', '-'))} "
        f"| {fmt(profiled.get('python_s', '-'))} "
        f"| {len(statements)} "
        f"| {fmt(longest['seconds']) if longest else '-'} | {top} |"
    )


def main(argv: list[str]) -> None:
    """Run the probe subcommand, or generate the data and run every case."""
    if argv[:1] == ["probe"]:
        probe(argv[1], argv[2], argv[3], argv[4] == "1")
        return
    json_path = argv[argv.index("--json") + 1] if "--json" in argv else None
    print(json.dumps(_machine(), indent=2))  # noqa: T201
    print("\nuptime before:", _uptime())  # noqa: T201
    results: list[dict[str, Any]] = []
    rows: list[str] = []
    with tempfile.TemporaryDirectory(prefix="engine_profile_data_") as tmp:
        path = Path(tmp) / "data.parquet"
        for width in (50, 200, 500):
            _write(path, ROWS, width)
            for call, case_width in CASES:
                if case_width != width:
                    continue
                runs = [run(call, path, profiled=False) for _ in range(2)]
                profiled = run(call, path, profiled=True)
                results.append(
                    {"call": call, "columns": width, "runs": runs, "profiled": profiled}
                )
                rows.append(_row(call, width, runs, profiled))
    print(  # noqa: T201
        "\n| path | columns | s | peak GB | DuckDB s | Python s | statements "
        "| longest s | largest operators |\n|---|---|---|---|---|---|---|---|---|"
    )
    for row in rows:
        print(row)  # noqa: T201
    if json_path:
        Path(json_path).write_text(json.dumps(results, indent=2))
    print("\nuptime after:", _uptime())  # noqa: T201


if __name__ == "__main__":
    main(sys.argv[1:])
