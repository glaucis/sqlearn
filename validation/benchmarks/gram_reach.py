"""Measure PCA learning data larger than memory (issue #66, spec §3 rule 3).

A Gram learn streams the centred rows through numpy in batches, so the data
need not fit in memory. This script writes a Parquet file larger than the
machine's RAM and, at a DuckDB ``memory_limit`` of 2 GB, times:

- ``learn``: ``sq.Pipeline([sq.decompose.pca()]).learn`` on the file, whole;
- ``gram``: ``sqlearn._gram.gram_matrix`` alone, the matrix the learn builds;
- ``covar``: DuckDB's own ``covar_pop`` of every pair of columns, the matrix
  the other two are measured against.

Each probe runs in a subprocess of its own, so that its peak memory
(``resource.getrusage(RUSAGE_SELF).ru_maxrss``: bytes on macOS, kilobytes on
Linux) is its own. A probe also reports the peak after its imports, before
any data, so that the baseline of the interpreter and numpy can be taken off.
The modelled total is ``check_fits``' 4 copies of the p-by-p matrix plus 3
batches (``_COPIES``, ``_BATCH_COPIES`` of ``sqlearn._gram``) on top of the
DuckDB limit. It prints Markdown tables. It measures; it decides nothing.

Run it with ``uv run python -m validation.benchmarks.gram_reach [rows
columns]``; the defaults are 12,500,000 rows of 200 columns, a file of about
20 GB. The data is generated by DuckDB from a fixed seed into a temporary
directory removed after. ``uptime`` is printed before and after: on a loaded
machine the numbers are estimates.
"""

import json
import resource
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import duckdb
import numpy as np

from validation.benchmarks.category_lookup import _machine

PAGE = "docs/benchmarks/gram-streaming.md"
"""The page of ``docs/benchmarks`` this script's numbers feed."""
GROUPS: tuple[str, ...] | None = None
"""The C++ groups it measures; None for every group (ADR 0072)."""

SEED = 0
"""The data comes from this seed: generated, never downloaded."""

ROWS = 12_500_000
"""The default rows: 20 GB as doubles at 200 columns."""

COLUMNS = 200
"""The default columns."""

LIMIT = "2GB"
"""DuckDB's ``memory_limit`` for every probe."""

LATENT = 11
"""The latent factors the columns are mixed from, so components are defined."""

ROW_GROUP = 20_000
"""The rows of a Parquet row group. DuckDB reads one row group per thread, so
the default 122,880 rows of 200 columns (200 MB) on 8 threads do not fit 2 GB."""


def _peak() -> int:
    """Return this process's peak resident bytes (macOS bytes, Linux KB)."""
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return peak if sys.platform == "darwin" else peak * 1024


def _uptime() -> str:
    return subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip()


def _column(j: int) -> str:
    """Return the SQL of column `j`: two latent factors and its own noise."""
    a, b = j % LATENT, (3 * j + 1) % LATENT

    def draw(salt: int) -> str:
        return f"((hash(i, {SEED + salt}) % 2000001)::DOUBLE - 1000000) / 1e6"

    return (
        f"{draw(a)} * {1 + j / 10} + {draw(b)} * {2 - j / 400} "
        f"+ {draw(1000 + j)} * {0.05 + j / 250} AS c{j}"
    )


def _write(path: Path, rows: int, columns: int, spill: Path) -> None:
    """Write `rows` rows of `columns` columns as Parquet with ``COPY``."""
    con = duckdb.connect()
    con.execute(f"SET temp_directory = '{spill}'")
    values = ", ".join(_column(j) for j in range(columns))
    con.execute(
        f"COPY (SELECT {values} FROM range({rows}) t(i)) TO '{path}' "
        f"(FORMAT parquet, ROW_GROUP_SIZE {ROW_GROUP})"
    )
    con.close()


def _connect(spill: str) -> duckdb.DuckDBPyConnection:
    con = duckdb.connect()
    con.execute(f"SET memory_limit = '{LIMIT}'")
    con.execute(f"SET temp_directory = '{spill}'")
    return con


def _covar(con: duckdb.DuckDBPyConnection, path: str, columns: int) -> np.ndarray:
    """Return DuckDB's ``covar_pop`` matrix of the file's columns."""
    pairs = [(i, j) for i in range(columns) for j in range(i, columns)]
    cov = np.zeros((columns, columns))
    # In groups, so that no statement holds tens of thousands of aggregates.
    for start in range(0, len(pairs), 2000):
        group = pairs[start : start + 2000]
        calls = ", ".join(f"covar_pop(c{i}, c{j})" for i, j in group)
        (flat,) = con.sql(f"SELECT [{calls}] FROM read_parquet('{path}')").fetchall()[0]
        for (i, j), value in zip(group, flat, strict=True):
            cov[i, j] = cov[j, i] = value
    return cov


def probe(way: str, path: str, columns: int, spill: str, out: str) -> None:
    """Run one way on the file in this process; print a JSON line."""
    import sqlearn as sq
    from sqlearn._gram import gram_matrix

    base = _peak()
    con = _connect(spill)
    names = [f"c{j}" for j in range(columns)]
    source = f"SELECT * FROM read_parquet('{path}')"
    start = time.perf_counter()
    if way == "learn":
        sq.set_config(connection=con)
        pca = sq.Pipeline([sq.decompose.pca()]).learn(path)["pca"]
        result = {
            "n": pca.n_samples_,
            "variances": list(pca.explained_variance_),
            "mean": list(pca.mean_),
        }
        np.save(out, np.array(pca.components_))
    elif way == "gram":
        avgs = ", ".join(f"avg(c{j})" for j in range(columns))
        means = con.sql(f"SELECT {avgs} FROM ({source})").fetchall()[0]
        (n,) = con.sql(f"SELECT count(*) FROM ({source})").fetchall()[0]
        gram = gram_matrix(con, source, names, dict(zip(names, means, strict=True)))
        np.save(out, gram / n)
        result = {"n": n}
    else:
        cov = _covar(con, path, columns)
        np.save(out, cov)
        result = {}
    result.update(s=round(time.perf_counter() - start, 1), peak=_peak(), base=base)
    print(json.dumps(result))  # noqa: T201


def _run(way: str, path: Path, columns: int, tmp: Path) -> dict:
    out = subprocess.run(
        [
            sys.executable,
            "-m",
            "validation.benchmarks.gram_reach",
            "probe",
            way,
            str(path),
            str(columns),
            str(tmp / "spill"),
            str(tmp / f"{way}.npy"),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if out.returncode:
        raise RuntimeError(f"{way} failed: {out.stderr.strip()[-1500:]}")
    return json.loads(out.stdout.strip().splitlines()[-1])


def _gb(value: int) -> str:
    return f"{value / 1e9:.2f}"


def main(rows: int = ROWS, columns: int = COLUMNS) -> None:
    """Generate the data, run every probe, print the tables."""
    if sys.argv[1:2] == ["probe"]:
        probe(sys.argv[2], sys.argv[3], int(sys.argv[4]), sys.argv[5], sys.argv[6])
        return
    if len(sys.argv) == 3:
        rows, columns = int(sys.argv[1]), int(sys.argv[2])
    print(json.dumps(_machine(), indent=2))  # noqa: T201
    print("\nuptime before:", _uptime(), flush=True)  # noqa: T201
    with tempfile.TemporaryDirectory(prefix="gram_reach_") as name:
        tmp = Path(name)
        path = tmp / "data.parquet"
        start = time.perf_counter()
        _write(path, rows, columns, tmp / "spill")
        size = path.stat().st_size
        print(  # noqa: T201
            f"\nwrote {rows:,} x {columns}: {_gb(size)} GB Parquet "
            f"({_gb(8 * rows * columns)} GB as doubles) in "
            f"{time.perf_counter() - start:.0f} s",
            flush=True,
        )
        results = {
            way: _run(way, path, columns, tmp) for way in ("learn", "gram", "covar")
        }
        cov = np.load(tmp / "covar.npy")
        gram = np.load(tmp / "gram.npy")
        spread = np.abs(cov).max()
        learn = results["learn"]
        values = np.linalg.eigvalsh(cov)[::-1] * rows / (rows - 1)
        vectors = np.linalg.eigh(cov)[1][:, ::-1].T
        got = np.load(tmp / "learn.npy")
        signs = np.sign(np.einsum("ij,ij->i", got, vectors))
        agree = {
            "gram vs covar_pop, max |difference| / max |covar_pop|": np.abs(
                gram - cov
            ).max()
            / spread,
            "learn's variances vs eigenvalues of covar_pop, max relative": np.max(
                np.abs(np.array(learn["variances"]) - values) / values
            ),
            "learn's components vs eigenvectors of covar_pop, max |difference|": np.abs(
                got * signs[:, None] - vectors
            ).max(),
        }
    fits = 8 * columns * (4 * columns + 3)
    batch = 8 * columns * min(100_000_000 // (8 * columns), 10**9)
    print(  # noqa: T201
        "\n| probe | s | peak GB | baseline GB | peak less baseline GB |"
        "\n|---|---|---|---|---|"
    )
    for way, r in results.items():
        print(  # noqa: T201
            f"| {way} | {r['s']} | {_gb(r['peak'])} | {_gb(r['base'])} | "
            f"{_gb(r['peak'] - r['base'])} |"
        )
    print(  # noqa: T201
        f"\nmodelled: DuckDB limit {LIMIT}; 4 matrices {_gb(4 * 8 * columns**2)} GB; "
        f"3 batches {_gb(3 * batch)} GB (batch of {_gb(batch)} GB); "
        f"check_fits size {_gb(fits)} GB"
    )
    print("\n| agreement | value |\n|---|---|")  # noqa: T201
    for label, value in agree.items():
        print(f"| {label} | {value:.2e} |")  # noqa: T201
    print("\nuptime after:", _uptime())  # noqa: T201


if __name__ == "__main__":
    main()
